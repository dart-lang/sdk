class Blake3Test {
  final hasher = ScalarBlake3();

  /// Checks empty input, and also lengths immediately before, at, and after 64-byte
  /// block and 1024-byte chunk boundaries against the independent reference.
  /// Chunk counts around powers of two exercise both complete and incomplete
  /// trees, including reductions that merge several pending subtrees.
  void test_blockAndTreeBoundaries() {
    var lengths = {
      0,
      for (var block = 1; block <= 129; block++)
        for (final delta in [-1, 0, 1]) block * 64 + delta,
      for (final chunks in [
        for (var i = 1; i <= 20; i++) i,
        31,
        32,
        33,
        63,
        64,
        65,
        127,
        128,
        129,
        255,
        256,
        257,
        511,
        512,
        513,
      ])
        for (final delta in [-1, 0, 1]) chunks * 1024 + delta,
    };
    var random = Random(538901);
    var bytes = _randomBytes(random, lengths.reduce(max));
    for (var length in lengths) {
      _check(Uint8List.sublistView(bytes, 0, length));
    }
  }

  void test_officialVectors() {
    for (var entry in _blake3Vectors.entries) {
      var input = Uint8List.fromList([
        for (var i = 0; i < entry.key; i++) i % 251,
      ]);
      var expected = _decodeHex(entry.value);
      expect(
        referenceBlake3(input),
        expected,
        reason: 'reference ${entry.key}',
      );
      _check(input, expected: expected);
    }
  }

  /// Hashes the same bytes at offsets 0..31 to cover aligned and unaligned views.
  /// Each view must match the digest of a standalone input, excluding the
  /// surrounding sentinel bytes. Comparing the entire backing buffer afterward
  /// checks that neither the input nor the sentinel bytes were modified.
  void test_offsetViews() {
    var random = Random(29);
    for (var length in [
      0,
      1,
      63,
      64,
      65,
      1023,
      1024,
      1025,
      4095,
      4096,
      4097,
      65537,
    ]) {
      var bytes = _randomBytes(random, length);
      var expected = referenceBlake3(bytes);
      for (var offset = 0; offset < 32; offset++) {
        var backing = Uint8List(length + 64)..fillRange(0, length + 64, 0xa5);
        backing.setRange(offset, offset + length, bytes);
        var before = Uint8List.fromList(backing);
        _check(
          Uint8List.sublistView(backing, offset, offset + length),
          expected: expected,
        );
        expect(
          backing,
          before,
          reason: 'input/sentinels $length offset $offset',
        );
      }
    }
  }

  void test_randomAndStructuredInputs() {
    var random = Random(20260920);
    for (var i = 0; i < 64; i++) {
      _check(_randomBytes(random, random.nextInt(20000)));
    }
    for (var length in [1, 65, 1024, 2049, 8192, 262145]) {
      for (var value in [0, 0x80, 0xff]) {
        _check(Uint8List(length)..fillRange(0, length, value));
      }
    }
  }

  /// Checks that one hasher can process differently sized, unmodifiable inputs
  /// while keeping every returned digest independently owned. Empty and small
  /// inputs after large inputs exercise the reset of reusable scratch storage.
  /// Mutating the input buffers and making later hash calls must leave saved
  /// digests intact. Mutating one digest must not affect other digests or the
  /// result of a subsequent hash call.
  void test_reuseAndOwnership() {
    var random = Random(7);
    var saved = <(Uint8List, Uint8List)>[];
    for (var length in [524289, 0, 1, 1024, 63, 8193, 0, 65, 4096]) {
      var bytes = _randomBytes(random, length);
      var expected = referenceBlake3(bytes);
      var digest = hasher.hash(bytes.asUnmodifiableView());
      expect(digest, expected);
      expect(digest.length, 32);
      saved.add((digest, Uint8List.fromList(digest)));
      bytes.fillRange(0, length, 0);
    }
    for (var (digest, expected) in saved) {
      expect(digest, expected, reason: 'retained digest changed');
    }
    saved.last.$1.fillRange(0, 32, 0);
    expect(hasher.hash(Uint8List(0)), _decodeHex(_blake3Vectors[0]!));
    for (var (digest, expected) in saved.take(saved.length - 1)) {
      expect(digest, expected, reason: 'digest storage aliases');
    }
  }

  void test_streamingLifecycle() {
    var sink = ScalarBlake3Sink();
    var expected = referenceBlake3(Uint8List.fromList([1, 2, 3]));
    var input = Uint8List.fromList([1, 2, 3]);
    sink.add(input);
    input.fillRange(0, input.length, 0);
    var first = sink.finish();
    expect(first, expected);
    var saved = sink.finish();
    first.fillRange(0, first.length, 0);
    expect(sink.finish(), expected);
    var empty = Uint8List(0);
    var next = Uint8List.fromList([4]);
    expect(() => sink.add(empty), throwsStateError);
    expect(() => sink.add(next), throwsStateError);

    for (var length in [65537, 0, 64, 1, 1024, 1025, 0]) {
      sink.reset();
      var bytes = Uint8List.fromList([
        for (var i = 0; i < length; i++) i & 255,
      ]);
      sink.add(bytes);
      expect(sink.finish(), referenceBlake3(bytes));
      expect(saved, expected);
    }
    sink.reset();
    sink.add(Uint8List(4097));
    sink.reset();
    expect(sink.finish(), referenceBlake3(Uint8List(0)));

    sink.reset();
    sink.add(Uint8List.fromList([1, 2, 3]));
    expect(sink.finish(), expected);
  }

  void test_streamingSplits() {
    var sink = ScalarBlake3Sink();
    var empty = Uint8List(0);
    var random = Random(563962);
    for (var length in [
      0,
      1,
      63,
      64,
      65,
      127,
      128,
      129,
      1023,
      1024,
      1025,
      2048,
      2049,
    ]) {
      var input = _randomBytes(random, length);
      var expected = referenceBlake3(input);
      for (var split = 0; split <= length; split++) {
        sink.reset();
        sink.add(Uint8List.sublistView(input, 0, split));
        sink.add(empty);
        sink.add(Uint8List.sublistView(input, split, length));
        expect(sink.finish(), expected, reason: '$length split $split');
      }
    }
  }

  void test_streamingTrees() {
    var random = Random(17);
    var sink = ScalarBlake3Sink();
    for (var chunks in [3, 4, 7, 8, 15, 16, 31, 32, 127, 128, 255, 256]) {
      for (var delta in [-1, 0, 1]) {
        var input = _randomBytes(random, chunks * 1024 + delta);
        sink.reset();
        for (var start = 0; start < input.length;) {
          var end = min(input.length, start + 1 + random.nextInt(8192));
          sink.add(Uint8List.sublistView(input, start, end));
          start = end;
        }
        expect(sink.finish(), referenceBlake3(input));
      }
    }
  }

  void test_streamingVectors() {
    var sink = ScalarBlake3Sink();
    for (var entry in _blake3Vectors.entries) {
      var input = Uint8List.fromList([
        for (var i = 0; i < entry.key; i++) i % 251,
      ]);
      var expected = _decodeHex(entry.value);
      for (var size in [1, 3, 4, 63, 64, 65, 1023, 1024, 1025, 16384]) {
        sink.reset();
        for (var start = 0; start < input.length; start += size) {
          sink.add(
            Uint8List.sublistView(
              input,
              start,
              min(start + size, input.length),
            ),
          );
        }
        expect(sink.finish(), expected, reason: '${entry.key} pieces of $size');
      }
    }
  }

  void test_streamingViews() {
    var random = Random(42);
    for (var length in [0, 63, 64, 65, 1023, 1024, 1025, 4097]) {
      var input = _randomBytes(random, length);
      var expected = referenceBlake3(input);
      for (var offset = 0; offset < 32; offset++) {
        var backing = Uint8List(length + 64)..fillRange(0, length + 64, 0xa5);
        backing.setRange(offset, offset + length, input);
        var original = Uint8List.fromList(backing);
        var view = Uint8List.sublistView(backing, offset, offset + length);
        var sink = ScalarBlake3Sink();
        sink.add(view.asUnmodifiableView());
        expect(backing, original);
        backing.fillRange(0, backing.length, 0);
        expect(sink.finish(), expected);

        sink.reset();
        sink.add(
          Uint8List.sublistView(
            original.asUnmodifiableView(),
            offset,
            offset + length,
          ),
        );
        expect(sink.finish(), expected);
      }
    }
  }

  void _check(Uint8List input, {Uint8List? expected}) {
    expected ??= referenceBlake3(input);
    expect(
      hasher.hash(input),
      expected,
      reason: 'length ${input.length}, offset ${input.offsetInBytes}',
    );
  }

  Uint8List _decodeHex(String hex) => Uint8List.fromList([
    for (var i = 0; i < hex.length; i += 2)
      int.parse(hex.substring(i, i + 2), radix: 16),
  ]);

  Uint8List _randomBytes(Random random, int length) =>
      Uint8List.fromList(List.generate(length, (_) => random.nextInt(256)));
}
