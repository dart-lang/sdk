void main() {
  // Avoid dart:mirrors so the same suite can run in AOT as well as JIT.
  group('Blake3', () {
    late Blake3Test suite;
    setUp(() => suite = Blake3Test());
    test('official vectors', () => suite.test_officialVectors());
    test(
      'block and tree boundaries',
      () => suite.test_blockAndTreeBoundaries(),
    );
    test('offset views', () => suite.test_offsetViews());
    test(
      'random and structured inputs',
      () => suite.test_randomAndStructuredInputs(),
    );
    test('reuse and ownership', () => suite.test_reuseAndOwnership());
    test('streaming official vectors', () => suite.test_streamingVectors());
    test('streaming split boundaries', () => suite.test_streamingSplits());
    test('streaming tree boundaries', () => suite.test_streamingTrees());
    test('streaming input views', () => suite.test_streamingViews());
    test('streaming lifecycle', () => suite.test_streamingLifecycle());
  });
}

