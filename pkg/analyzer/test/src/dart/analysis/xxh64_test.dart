  void test_detectsThreeBitCorruption() {
    var bytes = Uint8List(64);
    expect(xxh64(bytes), 0x257b09a147b82a19);
    bytes[7] ^= 0x80;
    bytes[36] ^= 0x04;
    bytes[39] ^= 0x80;
    expect(xxh64(bytes), 0x318d93e2db218f65);
    // The store retains only these low 32 bits.
    expect(xxh64(bytes) & 0xFFFFFFFF, isNot(0x47b82a19));
  }

  void test_detectsZeroToFF() {
    // Fletcher-16 treats 0 and 255 as equal, missing this corruption.
    var bytes = Uint8List(1024);
    var original = xxh64(bytes) & 0xFFFFFFFF;
    bytes.fillRange(0, bytes.length, 0xFF);
    expect(xxh64(bytes) & 0xFFFFFFFF, isNot(original));
  }

