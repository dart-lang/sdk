// This test ensures that, when generating assembly, symbol names that start
// with characters the assembler or linker treats specially are modified, so
// the symbols are not dropped from the assembled snapshot.
//
// On Apple platforms, all symbols are prefixed with '_' unless they already
// start with one, as the linker strips symbols starting with 'l'. Elsewhere,
// only symbols starting with 'L' are prefixed with '_', as the assembler
// treats them as local labels.

// OtherResources=check_snapshot_symbols_program.dart

import 'dart:io';

import 'package:expect/expect.dart';
import 'package:path/path.dart' as path;
import 'package:native_stack_traces/src/elf.dart' as elf;
import 'package:native_stack_traces/src/macho.dart' as macho;

import 'use_flag_test_helper.dart';

main(List<String> args) async {
  if (!isAOTRuntime) {
    return; // Running in JIT: AOT binaries not available.
  }

  if (Platform.isAndroid) {
    return; // SDK tree not available on the test device.
  }

  if (Platform.isWindows) {
    return; // Checking COFF symbols is not yet supported.
  }

  if (isSimulator || clangBuildToolsDir == null) {
    return; // Assembling the snapshot requires //buildtools for the target.
  }

  // These are the tools we need to be available to run on a given platform:
  if (!File(platformDill).existsSync()) {
    throw "Cannot run test as $platformDill does not exist";
  }
  if (!await testExecutable(genSnapshot)) {
    throw "Cannot run test as $genSnapshot not available";
  }

  await withTempDir('assembly-symbol-check-test', (String tempDir) async {
    final cwDir = path.dirname(Platform.script.toFilePath());
    final script = path.join(cwDir, 'check_snapshot_symbols_program.dart');
    final scriptDill = path.join(tempDir, 'program.dill');

    // Compile script to Kernel IR.
    await run(genKernel, <String>[
      '--aot',
      '--platform=$platformDill',
      '-o',
      scriptDill,
      script,
    ]);

    final assembly = path.join(tempDir, 'snapshot.S');
    final snapshot = path.join(tempDir, 'snapshot.so');
    await run(genSnapshot, <String>[
      '--snapshot-kind=app-aot-assembly',
      '--assembly=$assembly',
      scriptDill,
    ]);
    await assembleSnapshot(assembly, snapshot);

    checkSymbols(readSymbolNames(snapshot));
  });
}

final isApplePlatform = Platform.isMacOS || Platform.isIOS;

Set<String> readSymbolNames(String snapshot) {
  final names = <String>{};
  if (isApplePlatform) {
    final machO = macho.MachO.fromFile(snapshot);
    Expect.isNotNull(machO);
    for (final symbol in machO!.symbolTable.values) {
      // Skip N_STAB symbols to avoid having to handle special symbols like
      // N_OSO. N_STAB symbols that have corresponding non-N_STAB symbols use
      // the same name as their counterparts, so those names are checked.
      if (!symbol.isSymbolicDebugging) {
        names.add(symbol.name);
      }
    }
  } else {
    final elfFile = elf.Elf.fromFile(snapshot);
    Expect.isNotNull(elfFile);
    for (final symbol in elfFile!.staticSymbols) {
      // Ignore STT_NOTYPE symbols, as either it is the initial all-0 entry in
      // the symbol table or generated by the linker, not Dart.
      if (symbol.type != elf.SymbolType.STT_NOTYPE) {
        names.add(symbol.name);
      }
    }
  }
  return names;
}

bool isValidSymbol(String name) =>
    isApplePlatform ? name.startsWith('_') : !name.startsWith('L');

void checkSymbols(Set<String> names) {
  Expect.isNotEmpty(names);
  for (final name in names) {
    Expect.isTrue(isValidSymbol(name), 'Invalid symbol name "$name"');
  }

  // The functions in the program must be present under their modified names.
  final expected = isApplePlatform
      ? ['_leadingLowercaseL', '_LeadingUppercaseL', '_leadingUnderscore']
      : ['leadingLowercaseL', '_LeadingUppercaseL', '_leadingUnderscore'];
  for (final name in expected) {
    Expect.isTrue(names.contains(name), 'Missing symbol "$name"');
  }
}
